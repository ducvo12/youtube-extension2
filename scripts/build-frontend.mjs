import { watch } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distDir = path.join(rootDir, "frontend", "dist");
const shouldWatch = process.argv.includes("--watch");

const sourceFiles = [
  "frontend/src/content.js",
  "frontend/src/content/shared/storage-keys.js",
  "frontend/src/content/shared/dom-ids.js",
  "frontend/src/content/shared/caption-timing.js",
  "frontend/src/content/shared/state.js",
  "frontend/src/content/sidebar/diagnostics.js",
  "frontend/src/content/sidebar/caption-track-selector.js",
  "frontend/src/content/captions/transcript-parser.js",
  "frontend/src/content/youtube/youtube-page.js",
  "frontend/src/content/chat/chat.js",
  "frontend/src/content/chat/markdown.js",
  "frontend/src/content/chat/selected-caption.js",
  "frontend/src/content/translate.js",
  "frontend/src/content/captions/caption-river.js",
  "frontend/src/content/captions/player-caption-capture.js",
  "frontend/src/content/sidebar/sidebar.js",
  "frontend/src/content/lifecycle.js",
  "frontend/src/background.js",
  "frontend/src/page-caption-capturer.js",
];

async function buildContentScript() {
  await build({
    entryPoints: [path.join(rootDir, "frontend/src/content.js")],
    outfile: path.join(distDir, "content.js"),
    bundle: true,
    format: "iife",
    sourcemap: true,
    target: "chrome124",
  });
}

async function buildStandaloneScript(entryPoint, outfile) {
  await build({
    entryPoints: [path.join(rootDir, entryPoint)],
    outfile: path.join(distDir, outfile),
    bundle: true,
    format: "iife",
    sourcemap: true,
    target: "chrome124",
  });
}

async function buildFrontend() {
  await mkdir(distDir, { recursive: true });
  await Promise.all([
    buildContentScript(),
    buildStandaloneScript("frontend/src/background.js", "background.js"),
    buildStandaloneScript("frontend/src/page-caption-capturer.js", "page-caption-capturer.js"),
  ]);
}

async function writeBuildStamp() {
  await writeFile(
    path.join(distDir, ".build-note"),
    "Generated by npm run build:frontend. Edit source files outside frontend/dist.\n",
  );
}

await buildFrontend();
await writeBuildStamp();

console.log("Built frontend/dist");

if (shouldWatch) {
  let rebuildTimer = null;

  const scheduleRebuild = () => {
    clearTimeout(rebuildTimer);
    rebuildTimer = setTimeout(async () => {
      try {
        await buildFrontend();
        await writeBuildStamp();
        console.log(`Rebuilt frontend/dist at ${new Date().toLocaleTimeString()}`);
      } catch (error) {
        console.error(error);
      }
    }, 100);
  };

  for (const file of sourceFiles) {
    watch(path.join(rootDir, file), scheduleRebuild);
  }

  console.log("Watching frontend source files...");
}
